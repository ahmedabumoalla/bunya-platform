final _arabicLiteralKeys = <String, String>{
  for (final entry in _messages['ar']!.entries) entry.value: entry.key,
};

final _arabicStatusKeys = <String, String>{
  for (final entry in _statusMessages['ar']!.entries) entry.value: entry.key,
};

extension BunyaTranslations on BuildContext {
  String tr(String key) {
    final code = Localizations.localeOf(this).languageCode;
    return _messages[code]?[key] ?? _messages['ar']?[key] ?? key;
  }

  String localizedStatus(String raw) {
    final code = Localizations.localeOf(this).languageCode;
    final key = _statusKeys[raw];
    return key == null ? raw : (_statusMessages[code]?[key] ?? raw);
  }

  String localizedUiText(String value) {
    final code = Localizations.localeOf(this).languageCode;
    if (code == 'ar') return value;
    final trimmed = value.trim();
    final messageKey = _arabicLiteralKeys[trimmed];
    if (messageKey != null) {
      return value.replaceFirst(
        trimmed,
        _messages[code]?[messageKey] ?? trimmed,
      );
    }
    final statusKey = _arabicStatusKeys[trimmed];
    if (statusKey != null) {
      return value.replaceFirst(
        trimmed,
        _statusMessages[code]?[statusKey] ?? trimmed,
      );
    }
    return value;
  }

  String localizedSnapshot(Object? source, Object? translations) {
    final fallback = '${source ?? '—'}';
    final code = Localizations.localeOf(this).languageCode;
    if (code == 'ar' || translations is! Map) return fallback;
    final translated = '${translations[code] ?? ''}'.trim();
    return translated.isEmpty ? fallback : translated;
  }
}

class BunyaLanguageButton extends StatelessWidget {
  const BunyaLanguageButton({super.key});

  @override
  Widget build(BuildContext context) => IconButton(
    tooltip: context.tr('chooseLanguage'),
    icon: const Icon(Icons.translate_rounded),
    onPressed: () => showModalBottomSheet<void>(
      context: context,
      showDragHandle: true,
      builder: (sheetContext) => SafeArea(
        child: ListView(
          shrinkWrap: true,
          padding: const EdgeInsets.fromLTRB(16, 0, 16, 20),
          children: [
            Padding(
              padding: const EdgeInsets.symmetric(vertical: 8),
              child: Text(
                context.tr('chooseLanguage'),
                style: Theme.of(context).textTheme.titleLarge
                    ?.copyWith(fontWeight: FontWeight.w900),
              ),
            ),
            for (final locale in supportedBunyaLocales)
              ListTile(
                minTileHeight: 52,
                title: Text(bunyaLanguageNames[locale.languageCode]!),
                trailing:
                    locale.languageCode ==
                        Localizations.localeOf(context).languageCode
                    ? const Icon(Icons.check_circle_rounded)
                    : const Icon(Icons.circle_outlined),
                onTap: () async {
                  Navigator.pop(sheetContext);
                  await BunyaLocaleController.change(locale.languageCode);
                },
              ),
          ],
        ),
      ),
    ),
  );
}
