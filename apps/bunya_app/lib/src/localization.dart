  'bn': 'বাংলা',
  'fil': 'Filipino',
};

abstract final class BunyaLocaleController {
  static const _preferenceKey = 'bunya_locale';
  static final locale = ValueNotifier<Locale>(const Locale('ar'));

  static Future<void> initialize() async {
    final saved = (await SharedPreferences.getInstance()).getString(
      _preferenceKey,
    );
    if (saved != null && bunyaLanguageNames.containsKey(saved)) {
      locale.value = Locale(saved);
    }
  }

  static Future<void> change(String code) async {
    if (!bunyaLanguageNames.containsKey(code)) return;
    await (await SharedPreferences.getInstance()).setString(
      _preferenceKey,
      code,
    );
    try {
      final client = Supabase.instance.client;
      final user = client.auth.currentUser;
      if (user != null) {
        await client
            .from('profiles')
            .update({'preferred_locale': code})
            .eq('id', user.id)
            .timeout(const Duration(seconds: 4));
      }
    } catch (_) {
      // Local persistence remains available while offline.
    } finally {
      // Rebuild after the profile update so localized RPC payloads use the
      // same locale as the visible interface on their first request.
      locale.value = Locale(code);
    }
  }

  static Future<void> adoptProfileLocale(String? code) async {
    if (code == null || !bunyaLanguageNames.containsKey(code)) return;
    locale.value = Locale(code);
    await (await SharedPreferences.getInstance()).setString(
      _preferenceKey,
      code,
    );
  }
}

